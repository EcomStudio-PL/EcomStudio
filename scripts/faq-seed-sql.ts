/**
 * FAQ V1 — the SQL of migrations 0155 (the import) and 0156 (the pages),
 * generated from lib/faq-seed.ts. The content has ONE source, the TypeScript;
 * the migrations carry its SQL form, and scripts/faq-tests.ts fails when the
 * two disagree.
 *
 *   npm run faq:seed-sql -- --import   the generated block of 0155
 *   npm run faq:seed-sql -- --pages    the whole of 0156
 *   npm run faq:seed-sql -- --write    rewrite both files in place
 */
import { readFileSync, writeFileSync } from "fs";
import {
  FAQ_ABOUT_EXTRAS, FAQ_ABOUT_MAPPED, FAQ_CONTACT_LINKS, FAQ_CONTACT_NAV, FAQ_PAGE_SEED,
  FAQ_SEED_CATEGORIES, FAQ_SEED_ITEMS,
} from "../lib/faq-seed";

const lit = (value: string) => `'${value.replace(/'/g, "''")}'`;
const json = (value: unknown) => `${lit(JSON.stringify(value))}::jsonb`;
const textArray = (values: readonly string[]) => `array[${values.map(lit).join(", ")}]::text[]`;

export const IMPORT_BEGIN = "-- >>> generated by scripts/faq-seed-sql.ts from lib/faq-seed.ts — do not edit by hand";
export const IMPORT_END = "-- <<< generated";

export function importSql(): string {
  const positions = new Map<string, number>();
  const nextIn = (category: string) => {
    const n = (positions.get(category) ?? 0) + 10;
    positions.set(category, n);
    return n;
  };
  const cats = FAQ_SEED_CATEGORIES.map((c, i) =>
    `    (${lit(c.slug)}, ${json(c.name)}, ${(i + 1) * 10}, true, ${lit(c.topic)})`).join(",\n");
  const items = FAQ_SEED_ITEMS.map((it) => [
    lit(it.slug), lit(it.category), json(it.question), json(it.answer),
    it.draft ? json(it.draft) : "null::jsonb",
    String(nextIn(it.category)), String(it.visible), textArray(it.pages),
    String(Boolean(it.onlyPremiere)), String(Boolean(it.needsReview)),
    it.note ? lit(it.note) : "null::text", lit(it.key),
  ].join(", ")).map((row) => `      (${row})`).join(",\n");

  return `${IMPORT_BEGIN}
-- The 7 categories, the 30 questions of the brief and "Jak mogę kupić
-- dodatkowe kredyty?" from the old /plany FAQ — then the O nas questions the
-- brief has no twin for, read from the live about_faq section. One block, so
-- the flags below hold for every statement of the import. (The old /plany
-- answers were code, not data: they are in git, commit 330a367.)
do $faq$
declare
  v_about jsonb;
  v_item jsonb;
  v_n bigint;
  v_title text;
  v_slug text;
  v_cat text;
  v_after text;
  v_pos integer;
  v_known jsonb := ${json(FAQ_ABOUT_EXTRAS)};
  v_mapped text[] := ${textArray(FAQ_ABOUT_MAPPED)};
begin
  -- The import may set the import key; its history entries read "external".
  perform set_config('faq.internal', 'on', true);
  perform set_config('faq.action', 'external', true);

  insert into public.faq_categories (slug, name, position, visible, contact_topic) values
${cats}
  on conflict (slug) do nothing;

  insert into public.faq_items (slug, category_id, question, answer, draft_answer, position, visible, pages,
                                only_premiere, needs_review, review_note, import_key)
  select v.slug, c.id, v.question, v.answer, v.draft, v.position, v.visible, v.pages,
         v.only_premiere, v.needs_review, v.note, v.import_key
    from (values
${items}
    ) as v(slug, category, question, answer, draft, position, visible, pages, only_premiere, needs_review, note, import_key)
    join public.faq_categories c on c.slug = v.category
  on conflict do nothing;

  -- O nas: every question of the PUBLISHED about_faq section that is not one
  -- of the brief's, with the words it has today. A known one goes to its
  -- category and place; one an admin added goes to the first category.
  select e -> 'content' into v_about
    from public.cms_pages p, jsonb_array_elements(coalesce(p.published_snapshot, '[]'::jsonb)) e
   where p.slug = 'o-nas' and e ->> 'type' = 'about_faq'
   limit 1;
  if v_about is not null and jsonb_typeof(v_about -> 'items') = 'array' then
    for v_item, v_n in select x.value, x.ordinality from jsonb_array_elements(v_about -> 'items') with ordinality x loop
      v_title := btrim(coalesce(v_item -> 'title' ->> 'pl', ''));
      continue when v_title = '' or v_title = any(v_mapped);
      v_slug := null; v_cat := null; v_after := null;
      select k ->> 'slug', k ->> 'category', k ->> 'after' into v_slug, v_cat, v_after
        from jsonb_array_elements(v_known) k where k ->> 'title' = v_title limit 1;
      if v_slug is null then
        v_slug := left(trim(both '-' from regexp_replace(
                    lower(translate(v_title, 'ąćęłńóśźżĄĆĘŁŃÓŚŹŻ', 'acelnoszzacelnoszz')), '[^a-z0-9]+', '-', 'g')), 70);
        v_slug := coalesce(nullif(trim(both '-' from v_slug), ''), 'pytanie');
        if exists (select 1 from public.faq_items i where i.slug = v_slug and i.import_key is distinct from 'o-nas:' || (v_n - 1)) then
          v_slug := v_slug || '-' || v_n;
        end if;
        v_cat := 'pierwsze-kroki';
      end if;
      v_pos := coalesce(
        (select i.position + 5 from public.faq_items i where i.slug = v_after),
        (select max(i.position) + 10 from public.faq_items i join public.faq_categories c on c.id = i.category_id where c.slug = v_cat),
        10);
      insert into public.faq_items (slug, category_id, question, answer, position, visible, pages, review_note, import_key)
      select v_slug, c.id,
             (select coalesce(jsonb_object_agg(t.key, t.value), '{}'::jsonb)
                from jsonb_each(case when jsonb_typeof(v_item -> 'title') = 'object' then v_item -> 'title' else '{}'::jsonb end) t
               where t.key in ('pl', 'en', 'de') and jsonb_typeof(t.value) = 'string' and btrim(t.value #>> '{}') <> ''),
             (select coalesce(jsonb_object_agg(t.key, t.value), '{}'::jsonb)
                from jsonb_each(case when jsonb_typeof(v_item -> 'description') = 'object' then v_item -> 'description' else '{}'::jsonb end) t
               where t.key in ('pl', 'en', 'de') and jsonb_typeof(t.value) = 'string' and btrim(t.value #>> '{}') <> ''),
             v_pos,
             not coalesce((v_item ->> 'hidden')::boolean, false),
             array['faq', 'o-nas']::text[],
             'Import FAQ V1: pytanie ze strony O nas, którego nie ma w briefie — przeniesione z jego bieżącą treścią.',
             'o-nas:' || (v_n - 1)
        from public.faq_categories c where c.slug = v_cat
      on conflict do nothing;
    end loop;
  end if;

  perform set_config('faq.internal', '', true);
  perform set_config('faq.action', '', true);
end $faq$;
${IMPORT_END}`;
}

/** The JSON of one block as a published snapshot carries it. */
const ELEMENT = (b: string) => `jsonb_build_object(
            'id', ${b}.id, 'type', ${b}.type, 'sort_order', ${b}.sort_order,
            'visible', ${b}.visible, 'content', ${b}.content,
            'style', ${b}.style, 'code', ${b}.code,
            'analytics_id', ${b}.analytics_id, 'anchor', ${b}.anchor,
            'show_from', ${b}.show_from, 'show_until', ${b}.show_until,
            'audience', ${b}.audience
          )`;

/** A page's published state, kept as a version before it changes. */
function keepSql(pageVar: string, label: string, indent = "    "): string {
  return `insert into public.cms_page_versions (page_id, version, snapshot, seo, reason, label)
select p.id,
       coalesce((select max(v.version) from public.cms_page_versions v where v.page_id = p.id), 0) + 1,
       coalesce(p.published_snapshot, '[]'::jsonb), coalesce(p.seo, '{}'::jsonb), 'manual', ${lit(label)}
  from public.cms_pages p where p.id = ${pageVar};`.replace(/^/gm, indent);
}

/** The page's new published snapshot (v_snapshot) written and versioned. */
function publishSql(pageVar: string, label: string, indent = "    "): string {
  return `update public.cms_pages
   set published_snapshot = v_snapshot, status = 'published',
       published_at = now(), updated_at = now(), scheduled_at = null
 where id = ${pageVar};
insert into public.cms_page_versions (page_id, version, snapshot, seo, reason, label)
values (
  ${pageVar},
  coalesce((select max(v.version) from public.cms_page_versions v where v.page_id = ${pageVar}), 0) + 1,
  v_snapshot, coalesce((select p.seo from public.cms_pages p where p.id = ${pageVar}), '{}'::jsonb),
  'publish', ${lit(label)}
);`.replace(/^/gm, indent);
}

export function pagesSql(): string {
  const page = FAQ_PAGE_SEED;
  const links = FAQ_CONTACT_LINKS.map((l) => ({ title: l.title, from: l.from, to: l.to }));
  return `-- 0156 — FAQ V1, THE PAGES: /faq gets its section, Kontakt links to it,
-- the footer's "Pomoc" lists it, and O nas stops carrying its own questions.
--
-- GENERATED from lib/faq-seed.ts by \`npm run faq:seed-sql -- --pages\`. Do not
-- edit by hand: change the TypeScript and regenerate.
--
-- ORDER: 0155 first; the code that reads the FAQ base (faq_page, the new
-- about_faq, faq links on Kontakt) must be LIVE before this runs — an older
-- build draws nothing for faq_page and would show O nas without questions.
--
-- Content only. Each page is kept as it was in a version first ("Przed FAQ
-- V1", restorable in Strony WWW → Historia) and every step is guarded, so a
-- second run changes nothing. The change is made to the draft AND to the
-- published copy separately: an admin's unpublished draft is never published
-- by this file.
--   /faq     its one faq_page section (the page has none today), SEO, and the
--            footer group "Pomoc", right above Kontakt.
--   Kontakt  back in "Pomoc" (0154 had put it under "Firma"); each FAQ link
--            that still points at its old /plany address moves to the same
--            question on /faq; the VAT-invoice link gets its question's
--            address (it shows once that question is published). A link an
--            admin has changed since is left alone.
--   O nas    the about_faq section keeps its heading and loses its own list:
--            its questions are in the base (0155) and the section reads them.

set local lock_timeout = '10s';

-- The Kontakt links, mapped: only a tile still on its old address (or the
-- VAT tile with none) moves. Session-temporary, gone when the migration ends.
create or replace function pg_temp.faq_map_tiles(p_tiles jsonb, p_links jsonb)
returns jsonb
language sql
immutable
as $$
  select case when jsonb_typeof(p_tiles) <> 'array' then p_tiles else (
    select coalesce(jsonb_agg(
             case when l.value is null then t.value
                  else jsonb_set(t.value, '{url}', to_jsonb(l.value ->> 'to')) end
             order by t.ordinality), '[]'::jsonb)
      from jsonb_array_elements(p_tiles) with ordinality t
      left join lateral (
        select x.value from jsonb_array_elements(p_links) x
         where (x.value ->> 'from' is not null and t.value ->> 'url' = x.value ->> 'from')
            or (x.value ->> 'from' is null and coalesce(btrim(t.value ->> 'url'), '') = ''
                and t.value -> 'title' ->> 'pl' = x.value ->> 'title')
         limit 1
      ) l on true
  ) end;
$$;

do $faq_pages$
declare
  v_page uuid;
  v_snapshot jsonb;
  v_links jsonb := ${json(links)};
  v_published jsonb;
begin
  /* ── /faq ─────────────────────────────────────────────────────────────── */
  insert into public.cms_pages (slug, title, status, kind)
  values ('faq', 'FAQ', 'draft', 'standard')
  on conflict (slug) do nothing;
  select id into v_page from public.cms_pages where slug = 'faq';

  if not exists (select 1 from public.cms_blocks b where b.page_id = v_page and b.type = 'faq_page') then
${keepSql("v_page", "Przed FAQ V1")}
    insert into public.cms_blocks (page_id, sort_order, type, content, style, anchor, analytics_id)
    values (v_page, 0, 'faq_page', ${json(page.content)}, ${json(page.style)}, null, ${lit(page.analyticsId)});
    update public.cms_pages
       set seo = ${json(page.seo)},
           nav_group = ${lit(page.navGroup)}, nav_order = ${page.navOrder},
           header_mode = 'global', footer_mode = 'global', updated_at = now()
     where id = v_page;
    -- What was published stays published; the new section joins it.
    select coalesce(p.published_snapshot, '[]'::jsonb) || coalesce((
             select jsonb_agg(${ELEMENT("b")})
               from public.cms_blocks b where b.page_id = v_page and b.type = 'faq_page'), '[]'::jsonb)
      into v_snapshot
      from public.cms_pages p where p.id = v_page;
${publishSql("v_page", "FAQ V1")}
  else
    raise notice 'faq: the faq_page section is already there, nothing written';
  end if;

  /* ── Kontakt ──────────────────────────────────────────────────────────── */
  select id into v_page from public.cms_pages where slug = 'kontakt';
  if v_page is not null then
    update public.cms_pages
       set nav_group = ${lit(FAQ_CONTACT_NAV.navGroup)}, nav_order = ${FAQ_CONTACT_NAV.navOrder}, updated_at = now()
     where id = v_page and nav_group is distinct from ${lit(FAQ_CONTACT_NAV.navGroup)};

    select coalesce(p.published_snapshot, '[]'::jsonb) into v_published from public.cms_pages p where p.id = v_page;
    select coalesce(jsonb_agg(
             case when e.value ->> 'type' = 'contact_page' and jsonb_typeof(e.value -> 'content' -> 'tiles') = 'array'
                  then jsonb_set(e.value, '{content,tiles}', pg_temp.faq_map_tiles(e.value -> 'content' -> 'tiles', v_links))
                  else e.value end
             order by e.ordinality), '[]'::jsonb)
      into v_snapshot
      from jsonb_array_elements(v_published) with ordinality e;

    if v_snapshot is distinct from v_published then
${keepSql("v_page", "Przed FAQ V1", "      ")}
${publishSql("v_page", "FAQ V1", "      ")}
    else
      raise notice 'kontakt: no published FAQ link to move';
    end if;
    -- The draft, on its own: the same links, nothing else touched.
    update public.cms_blocks b
       set content = jsonb_set(b.content, '{tiles}', pg_temp.faq_map_tiles(b.content -> 'tiles', v_links)), updated_at = now()
     where b.page_id = v_page and b.type = 'contact_page' and jsonb_typeof(b.content -> 'tiles') = 'array'
       and pg_temp.faq_map_tiles(b.content -> 'tiles', v_links) is distinct from b.content -> 'tiles';
  end if;

  /* ── O nas ────────────────────────────────────────────────────────────── */
  select id into v_page from public.cms_pages where slug = 'o-nas';
  if v_page is not null then
    select coalesce(p.published_snapshot, '[]'::jsonb) into v_published from public.cms_pages p where p.id = v_page;
    select coalesce(jsonb_agg(
             case when e.value ->> 'type' = 'about_faq' and e.value -> 'content' ? 'items'
                  then jsonb_set(e.value, '{content}', (e.value -> 'content') - 'items')
                  else e.value end
             order by e.ordinality), '[]'::jsonb)
      into v_snapshot
      from jsonb_array_elements(v_published) with ordinality e;

    if v_snapshot is distinct from v_published then
${keepSql("v_page", "Przed FAQ V1", "      ")}
${publishSql("v_page", "FAQ V1", "      ")}
    else
      raise notice 'o-nas: about_faq already reads the FAQ base';
    end if;
    update public.cms_blocks set content = content - 'items', updated_at = now()
     where page_id = v_page and type = 'about_faq' and content ? 'items';
  end if;
end $faq_pages$;
`;
}

const IMPORT_FILE = "supabase/migrations/0155_faq_v1.sql";
const PAGES_FILE = "supabase/migrations/0156_faq_pages.sql";

/** 0155 with its generated block replaced by `block`. */
export function withImport(file: string, block: string): string {
  const start = file.indexOf(IMPORT_BEGIN);
  const end = file.indexOf(IMPORT_END);
  if (start < 0 || end < start) throw new Error("0155: generated markers missing");
  return file.slice(0, start) + block + file.slice(end + IMPORT_END.length);
}

const arg = process.argv.slice(2);
if (arg.includes("--write")) {
  writeFileSync(IMPORT_FILE, withImport(readFileSync(IMPORT_FILE, "utf8"), importSql()));
  writeFileSync(PAGES_FILE, pagesSql());
  console.log(`wrote ${IMPORT_FILE} (generated block) and ${PAGES_FILE}`);
} else if (arg.includes("--pages")) {
  process.stdout.write(pagesSql());
} else if (arg.includes("--import")) {
  process.stdout.write(`${importSql()}\n`);
}
