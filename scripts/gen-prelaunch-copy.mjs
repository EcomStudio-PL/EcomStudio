#!/usr/bin/env node
/**
 * GENERATES supabase/migrations/0145_prelaunch_copy.sql — the launch page's
 * V2 copy, written into the CMS block that holds the live words.
 *
 * WHY A MIGRATION AND NOT A DICTIONARY EDIT. The live copy of "/" is not the
 * shipped dictionary: the launch block was seeded FROM it, so production holds
 * its own copy of every line (31 of 32 keys) and a dictionary change alone
 * changes nothing a visitor sees. The V2 brief rewrites those lines (no video
 * promise, the new hero, gated benefits), so the stored copy has to move.
 *
 * WHAT IT MAY TOUCH — ONLY UNTOUCHED DEFAULTS. Per key and per language the
 * stored value is replaced when it is absent or still EXACTLY the old shipped
 * default (git efec08f, compared after trimming and CRLF normalisation).
 * Anything an admin wrote stays as it is. New V2 keys are added with their
 * defaults (an empty default is written as "" so the key exists and the
 * inline editor can patch it — review-cms C, the every-key invariant).
 *
 * The draft (cms_blocks.content) and the published snapshot get the same
 * deterministic transform, so a draft that equalled the snapshot still does
 * (the inline editor refuses `draft_diverged`). A cms_page_versions row with
 * the snapshot AS IT WAS is written first, and only when something changes,
 * so Strony WWW → Historia can restore the pre-V2 copy. Re-running changes
 * nothing.
 *
 *   node scripts/gen-prelaunch-copy.mjs            # writes the migration
 *   node scripts/gen-prelaunch-copy.mjs --check    # exits 1 if it is stale
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const OLD_REF = "efec08f";
const OUT = "supabase/migrations/0145_prelaunch_copy.sql";
const LOCALES = ["pl", "en", "de"];
/** Plain media keys in the bag (no copy to migrate) — but each must EXIST as
 *  an object, like every launch key: the builder normalises a missing one on
 *  first open (a write without a version that also trips an open inline
 *  editor's conflict check), so 0145 adds it instead. */
const SKIP = new Set(["hero.image"]);
const OBJECT_KEYS = [...SKIP];

// LAUNCH_FIELDS straight from the module the renderer uses — never a copy.
const dir = mkdtempSync(join(tmpdir(), "gen-prelaunch-copy-"));
const entry = join(dir, "entry.ts");
writeFileSync(entry, `export { LAUNCH_FIELDS } from "${process.cwd()}/lib/server/launch-page";\n`);
require("esbuild").buildSync({
  entryPoints: [entry], bundle: true, platform: "node", format: "cjs", outfile: join(dir, "out.cjs"),
  alias: { "server-only": `${process.cwd()}/scripts/server-only-stub.js`, "@": process.cwd() }, logLevel: "error",
});
const { LAUNCH_FIELDS } = require(join(dir, "out.cjs"));

const oldDict = (l) => JSON.parse(execFileSync("git", ["show", `${OLD_REF}:lib/i18n/dictionaries/${l}.json`], { encoding: "utf8" }));
const newDict = (l) => JSON.parse(readFileSync(`lib/i18n/dictionaries/${l}.json`, "utf8"));

const map = {};
for (const key of LAUNCH_FIELDS) {
  if (SKIP.has(key)) continue;
  for (const l of LOCALES) {
    const oldLaunch = oldDict(l).launch ?? {};
    const nd = newDict(l);
    const merged = { ...(nd.prelaunch ?? {}), ...(nd.launch ?? {}) };
    const oldV = typeof oldLaunch[key] === "string" ? oldLaunch[key] : null;
    const newV = typeof merged[key] === "string" ? merged[key] : "";
    (map[key] ??= {})[l] = { old: oldV, new: newV };
  }
}

const json = JSON.stringify(map);
if (json.includes("$copy$")) throw new Error("copy contains the dollar-quote tag");

const sql = `-- 0145 — PRE-LAUNCH LANDING V2: the launch page's new copy, in the CMS block.
--
-- GENERATED by scripts/gen-prelaunch-copy.mjs from the dictionaries (old =
-- git ${OLD_REF}, new = this commit). Do not edit by hand; re-run the script.
--
-- Per key and language: a value that is absent or still the OLD shipped
-- default becomes the NEW default; anything an admin wrote is left alone. New
-- V2 keys are added (an empty default as "", so the key exists for the inline
-- editor; the media key hero.image is added as {} when missing). Draft and
-- published snapshot get the same transform; a
-- cms_page_versions row with the snapshot as it was is written first, only
-- when something changes. Idempotent.
--
-- ORDER: apply AFTER the V2 code serves "/" (design R2.5): the old renderer
-- does not resolve value tokens such as {credits}. To roll the code back after
-- this file, first restore the version labelled below in Strony WWW → Historia.

do $do$
declare
  v_map constant jsonb := $copy$${json}$copy$::jsonb;
  v_objects constant text[] := array[${OBJECT_KEYS.map((k) => `'${k}'`).join(", ")}];
  v_page uuid;
  v_seo jsonb;
  v_snap jsonb;
  v_block uuid;
  v_draft jsonb;
  v_idx int;
  v_old_content jsonb;
  v_new_draft jsonb;
  v_new_snap_content jsonb;
  v_version int;
  v_target jsonb;
  v_out jsonb;
  v_key text;
  v_loc text;
  v_pair jsonb;
  v_cur text;
  v_fields jsonb;
  v_obj jsonb;
  v_pass int;
begin
  -- The launch page: the homepage when it is the launch page, else the seeded one.
  select p.id, p.seo, p.published_snapshot into v_page, v_seo, v_snap
    from public.cms_pages p
    where p.kind = 'launch'
    order by p.is_homepage desc, (p.slug = 'premiera') desc, p.sort_order
    limit 1
    for update;
  if v_page is null then
    raise notice '0145: no launch page — nothing to do';
    return;
  end if;

  select b.id, b.content into v_block, v_draft
    from public.cms_blocks b
    where b.page_id = v_page and b.type = 'launch'
    order by b.sort_order, b.id
    limit 1
    for update;
  if v_block is null then
    raise notice '0145: the launch page has no launch block — nothing to do';
    return;
  end if;

  v_idx := null;
  if jsonb_typeof(v_snap) = 'array' then
    select (e.ordinality - 1)::int into v_idx
      from jsonb_array_elements(v_snap) with ordinality as e(value, ordinality)
      where e.value ->> 'id' = v_block::text
      limit 1;
  end if;
  v_old_content := case when v_idx is null then null else v_snap -> v_idx -> 'content' end;

  -- Pass 1 = the draft, pass 2 = the published content (when there is one).
  for v_pass in 1..2 loop
    v_target := case when v_pass = 1 then coalesce(v_draft, '{}'::jsonb) else v_old_content end;
    if v_target is null then
      v_out := null;
    else
      v_fields := coalesce(v_target -> 'fields', '{}'::jsonb);
      if jsonb_typeof(v_fields) <> 'object' then v_fields := '{}'::jsonb; end if;
      for v_key in select jsonb_object_keys(v_map) loop
        v_obj := v_fields -> v_key;
        if v_obj is null or jsonb_typeof(v_obj) <> 'object' then v_obj := '{}'::jsonb; end if;
        for v_loc in select jsonb_object_keys(v_map -> v_key) loop
          v_pair := v_map -> v_key -> v_loc;
          v_cur := v_obj ->> v_loc;
          if v_cur is null
             or (v_pair ->> 'old' is not null
                 and replace(btrim(v_cur), E'\\r\\n', E'\\n') = replace(btrim(v_pair ->> 'old'), E'\\r\\n', E'\\n')) then
            v_obj := v_obj || jsonb_build_object(v_loc, v_pair ->> 'new');
          end if;
        end loop;
        v_fields := v_fields || jsonb_build_object(v_key, v_obj);
      end loop;
      foreach v_key in array v_objects loop
        if jsonb_typeof(v_fields -> v_key) is distinct from 'object' then
          v_fields := v_fields || jsonb_build_object(v_key, '{}'::jsonb);
        end if;
      end loop;
      v_out := v_target || jsonb_build_object('fields', v_fields);
    end if;
    if v_pass = 1 then v_new_draft := v_out; else v_new_snap_content := v_out; end if;
  end loop;

  if v_new_draft is not distinct from v_draft
     and v_new_snap_content is not distinct from v_old_content then
    raise notice '0145: the launch copy is already current — nothing changed';
    return;
  end if;

  -- The snapshot as it was, first: Strony WWW → Historia can restore it.
  if v_old_content is not null then
    select coalesce(max(version), 0) + 1 into v_version from public.cms_page_versions where page_id = v_page;
    insert into public.cms_page_versions (page_id, version, snapshot, seo, reason, label)
    values (v_page, v_version, v_snap, coalesce(v_seo, '{}'::jsonb), 'manual',
            'Landing V2 — treści sprzed aktualizacji (0145)');
  end if;

  if v_new_draft is distinct from v_draft then
    update public.cms_blocks set content = v_new_draft, updated_at = now() where id = v_block;
  end if;
  if v_old_content is not null and v_new_snap_content is distinct from v_old_content then
    update public.cms_pages
      set published_snapshot = jsonb_set(v_snap, array[v_idx::text, 'content'], v_new_snap_content, false),
          updated_at = now()
      where id = v_page;
  end if;
  raise notice '0145: launch copy updated (draft %, published %)',
    v_new_draft is distinct from v_draft, v_new_snap_content is distinct from v_old_content;
end
$do$;
`;

if (/drop|delete/i.test(sql)) throw new Error("the generated SQL contains a forbidden word (drop/delete)");

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing */ }
  if (current !== sql) { console.error(`${OUT} is stale — run node scripts/gen-prelaunch-copy.mjs`); process.exit(1); }
  console.log(`${OUT} is current`);
} else {
  writeFileSync(OUT, sql);
  console.log(`wrote ${OUT} (${Object.keys(map).length} keys × ${LOCALES.length} languages)`);
}
