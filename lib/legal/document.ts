/**
 * A LEGAL TEXT, READ FOR DISPLAY — WITHOUT CHANGING A CHARACTER OF IT.
 *
 * The documents arrive as plain text with their own conventions: a title on
 * the first line, a header with "Wersja:" and "Data wejścia w życie:",
 * "Rozdział I." and "§ 1." headings (Regulamin), "1. …" / "15.1. …" headings
 * (the policies), numbered points ("1. ", nested with four spaces per level),
 * "- " rows, continuation lines indented by three spaces, annexes and a
 * version history.
 *
 * parseLegalText turns EVERY SOURCE LINE INTO EXACTLY ONE NODE (blank lines
 * become gaps), and every node keeps the line's text verbatim — the number,
 * the dash and the "§" included, so numbering is never re-generated by a
 * browser or a PDF library. What changes is only how a line looks: a heading
 * is bigger and gets an anchor, a point gets a hanging indent. The page, the
 * PDF and the 1:1 test all use this one function, and legalPlainText() is
 * the proof that nothing was dropped: normalised for whitespace, it equals
 * the source.
 *
 * Heading detection is deliberately narrow (a one-line paragraph that looks
 * like "Rozdział …", "Załącznik …", "§ N.", "N." / "N.N." and does not end
 * like a sentence, or "Historia wersji"). A line it does not recognise is
 * shown as an ordinary paragraph — never hidden, never merged.
 *
 * Pure and isomorphic: the public page, the admin preview and the PDF route
 * import it.
 */

export type LegalHeading = { id: string; text: string; level: 2 | 3 };

export type LegalNode =
  | { kind: "title"; text: string }
  | { kind: "meta"; text: string }
  | { kind: "heading"; level: 2 | 3; text: string; id: string }
  /** A plain line. `indent` is the number of leading spaces in the source
   *  (a continuation of a point is indented by three). */
  | { kind: "para"; text: string; indent: number }
  /** A numbered point or a "- " row: `marker` is "1.", "15.1." or "-",
   *  exactly as written; `depth` 0, 1, 2 … from the indentation. */
  | { kind: "item"; marker: string; text: string; depth: number; bullet: boolean }
  /** One or more blank lines. */
  | { kind: "gap" };

export type LegalOutline = {
  title: string | null;
  nodes: LegalNode[];
  headings: LegalHeading[];
};

const CHAPTER = /^Rozdział\s+([IVXLCDM]+)\.\s+\S/;
const ANNEX = /^Załącznik\b/;
const HISTORY = /^Historia wersji$/;
const PARAGRAPH = /^§\s*(\d+[a-z]?)\.\s+\S/;
const NUMBERED = /^(\d+(?:\.\d+)*)\.\s+\S/;
const SENTENCE_END = /[.:;,…]$/;

const ITEM = /^(\s*)(\d+(?:\.\d+)*\.)\s+(.*)$/;
const BULLET = /^(\s*)([-–•])\s+(.*)$/;
const INDENTED = /^(\s+)(\S.*)$/;
const FRONT_FACT = /^(Wersja|Data wejścia w życie):/;

const isBlank = (line: string) => line.trim() === "";

/** Lower-case ASCII slug of a heading, for an anchor id. */
function slugOf(text: string): string {
  const map: Record<string, string> = { ą: "a", ć: "c", ę: "e", ł: "l", ń: "n", ó: "o", ś: "s", ź: "z", ż: "z" };
  return text
    .toLowerCase()
    .replace(/[ąćęłńóśźż]/g, (c) => map[c] ?? c)
    .normalize("NFKD").replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);
}

type HeadingGuess = { level: 2 | 3; id: string; kind: "chapter" | "paragraph" | "numbered" | "other" };

function headingGuess(line: string): HeadingGuess | null {
  const text = line.trim();
  if (!text || text.length > 160 || text !== line.replace(/\s+$/, "")) return null;
  if (HISTORY.test(text)) return { level: 2, id: "historia-wersji", kind: "other" };
  if (SENTENCE_END.test(text)) return null;
  const ch = CHAPTER.exec(text);
  if (ch) return { level: 2, id: `rozdzial-${ch[1].toLowerCase()}`, kind: "chapter" };
  if (ANNEX.test(text)) return { level: 2, id: slugOf(text.split(".")[0]) || "zalacznik", kind: "other" };
  const par = PARAGRAPH.exec(text);
  if (par) return { level: 3, id: `par-${par[1]}`, kind: "paragraph" };
  const num = NUMBERED.exec(text);
  if (num) {
    const parts = num[1].split(".");
    return { level: parts.length > 1 ? 3 : 2, id: `pkt-${parts.join("-")}`, kind: "numbered" };
  }
  return null;
}

/** Group the lines into paragraphs: runs of non-blank lines, with the blank
 *  runs between them kept as gaps. */
function blocksOf(lines: string[]): ({ gap: true } | { gap: false; lines: string[] })[] {
  const out: ({ gap: true } | { gap: false; lines: string[] })[] = [];
  let cur: string[] | null = null;
  for (const line of lines) {
    if (isBlank(line)) {
      if (cur) { out.push({ gap: false, lines: cur }); cur = null; }
      if (out.length === 0 || !("gap" in out[out.length - 1] && out[out.length - 1].gap)) out.push({ gap: true });
    } else {
      (cur ??= []).push(line);
    }
  }
  if (cur) out.push({ gap: false, lines: cur });
  return out;
}

function lineNode(line: string): LegalNode {
  const item = ITEM.exec(line);
  if (item) {
    return { kind: "item", marker: item[2], text: item[3], depth: Math.round(item[1].length / 4), bullet: false };
  }
  const bullet = BULLET.exec(line);
  if (bullet) {
    return { kind: "item", marker: bullet[2], text: bullet[3], depth: Math.round(bullet[1].length / 4), bullet: true };
  }
  const indented = INDENTED.exec(line);
  if (indented) return { kind: "para", text: indented[2], indent: indented[1].length };
  return { kind: "para", text: line, indent: 0 };
}

export function parseLegalText(raw: string): LegalOutline {
  const text = raw.replace(/\r\n?/g, "\n");
  const lines = text.split("\n");
  const blocks = blocksOf(lines);
  const nodes: LegalNode[] = [];
  const headings: LegalHeading[] = [];
  // Every id handed out so far: "pkt-1-2" (a "1.2." heading) and the second
  // "1." heading's "pkt-1" + "-2" must not end up the same anchor.
  const used = new Set<string>();
  const uniqueId = (id: string) => {
    let candidate = id;
    for (let n = 2; used.has(candidate); n += 1) candidate = `${id}-${n}`;
    used.add(candidate);
    return candidate;
  };

  let title: string | null = null;
  let i = 0;
  // Leading gaps.
  while (i < blocks.length && blocks[i].gap) { nodes.push({ kind: "gap" }); i += 1; }

  // THE TITLE: the first line. The rest of its paragraph is header text.
  if (i < blocks.length) {
    const first = blocks[i] as { gap: false; lines: string[] };
    title = first.lines[0].trim();
    nodes.push({ kind: "title", text: title });
    for (const l of first.lines.slice(1)) nodes.push({ kind: "meta", text: l.trim() });
    i += 1;
  }

  // THE HEADER: the paragraphs right after the title, up to and including the
  // one that states the version or the effective date (at most three).
  let frontEnd = -1;
  for (let j = i, seen = 0; j < blocks.length && seen < 3; j += 1) {
    const b = blocks[j];
    if (b.gap) continue;
    seen += 1;
    if (b.lines.some((l) => FRONT_FACT.test(l.trim()))) { frontEnd = j; break; }
  }
  if (frontEnd >= 0) {
    for (; i <= frontEnd; i += 1) {
      const b = blocks[i];
      if (b.gap) { nodes.push({ kind: "gap" }); continue; }
      for (const l of b.lines) nodes.push({ kind: "meta", text: l.trim() });
    }
  }

  // THE BODY. Two passes: first decide the headings, then their levels — a
  // "§" heading is a chapter's child only when the document has chapters.
  const body = blocks.slice(i);
  const guesses = body.map((b) => (!b.gap && b.lines.length === 1 ? headingGuess(b.lines[0]) : null));
  const hasChapters = guesses.some((g) => g?.kind === "chapter");
  body.forEach((b, k) => {
    if (b.gap) { nodes.push({ kind: "gap" }); return; }
    const g = guesses[k];
    if (g) {
      const level: 2 | 3 = g.kind === "paragraph" && !hasChapters ? 2 : g.level;
      const id = uniqueId(g.id);
      const textOf = b.lines[0].trim();
      nodes.push({ kind: "heading", level, text: textOf, id });
      headings.push({ id, text: textOf, level });
      return;
    }
    for (const l of b.lines) nodes.push(lineNode(l));
  });

  return { title, nodes, headings };
}

/** The text a node shows, exactly (the marker of a point included). */
export function nodeText(node: LegalNode): string {
  switch (node.kind) {
    case "item": return `${node.marker} ${node.text}`;
    case "gap": return "";
    default: return node.text;
  }
}

/** Everything a reader sees, in order — for the 1:1 comparison with the
 *  source (compare after normaliseForCompare on both sides). */
export function legalPlainText(outline: LegalOutline): string {
  return outline.nodes.map(nodeText).join("\n");
}

/** The comparison's only tolerance: runs of whitespace (line breaks,
 *  indentation, the gap between a number and its text) count as one space. */
export function normaliseForCompare(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

export type LinkSegment = { text: string; href?: string };

// A web address runs to the next space, angle bracket or quotation mark —
// Polish „…” and the other typographic quotes included, so a quoted address
// does not carry the closing quote into its link.
const LINKS = /(https?:\/\/[^\s<>"'„”“‚‘’«»]+)|([A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,})/g;

/** The end of a sentence is not part of an address: trailing punctuation goes,
 *  and so does a ")" or "]" the address did not open itself. */
function trimAddress(value: string): string {
  let v = value;
  for (;;) {
    const last = v.slice(-1);
    if (/[.,;:!?]/.test(last)) { v = v.slice(0, -1); continue; }
    if (last === ")" && (v.match(/\(/g) ?? []).length < (v.match(/\)/g) ?? []).length) { v = v.slice(0, -1); continue; }
    if (last === "]" && (v.match(/\[/g) ?? []).length < (v.match(/\]/g) ?? []).length) { v = v.slice(0, -1); continue; }
    return v;
  }
}

/** Split a line into plain text and links (web addresses and e-mail
 *  addresses), keeping every character visible as it was. */
export function splitLinks(text: string): LinkSegment[] {
  const out: LinkSegment[] = [];
  let last = 0;
  for (const m of text.matchAll(LINKS)) {
    const start = m.index ?? 0;
    const value = m[1] ? trimAddress(m[0]) : m[0];
    if (m[1] && !/^https?:\/\/[^/]/.test(value)) continue;
    if (start > last) out.push({ text: text.slice(last, start) });
    out.push({ text: value, href: m[1] ? value : `mailto:${value}` });
    last = start + value.length;
  }
  if (last < text.length) out.push({ text: text.slice(last) });
  return out.length > 0 ? out : [{ text }];
}
